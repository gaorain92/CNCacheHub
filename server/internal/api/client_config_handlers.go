// Package api: 客户端配置生成器（PRD §9.5）。
//
// 生成器按 client 来源 URL（X-Forwarded-Proto / r.TLS / r.Host 推断），
// 把每个 registry upstream 转成对应客户端格式：
//   - Docker Engine daemon.json
//   - containerd hosts.toml（每个上游一个文件）
//   - k3s / rke2 registries.yaml
//   - SteamCMD（Phase 2）
//
// §9.5.4 还提供一键 zip 配置包导出（POST /api/client-config/bundle）：
// 包含 daemon.json / containerd hosts / k3s registries / steamcmd docker-compose
// / resource-accelerators (playwright / puppeteer / terraformrc / helm-repos.sh)
// / verify.sh / README.md。
