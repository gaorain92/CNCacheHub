// bundleFile 是 zip 内的单个文件。
type bundleFile struct {
	path    string // zip 内路径，例 "docker/daemon.json"
	content []byte
}

// buildClientConfigBundle 构造配置包的所有文件（不写 zip）。
//
// 返回的 []bundleFile 顺序就是 zip 内顺序（unzip 工具按字母序排）。
// 每个文件都有自己的 header（容器化 + 注释 + 内容）。
//
// 设计：分开"build"和"write zip"两步，让 build 能在没注册表时也调，方便测试。
func buildClientConfigBundle(baseURL string, regs []storage.Registry) []bundleFile {
	now := timeNowUnix()
	files := []bundleFile{}

	// 1. docker/daemon.json
	files = append(files, bundleFile{
		path:    "docker/daemon.json",
		content: generateDockerDaemonJSON(baseURL, regs),
	})

	// 2. containerd/<hostname>/hosts.toml — 每个 enabled upstream 一个
	for _, reg := range regs {
		if !reg.Enabled {
			continue
		}
		host := registryHostnameFromUpstream(reg.Name)
		files = append(files, bundleFile{
			path:    fmt.Sprintf("containerd/%s/hosts.toml", host),
			content: []byte(generateContainerdHostsTOML(clientConfigContextFromURL(baseURL, reg, host))),
		})
	}

	// 3. k3s/registries.yaml — 包含所有 enabled upstream
	files = append(files, bundleFile{
		path:    "k3s/registries.yaml",
		content: generateK3sRegistriesYAMLMulti(baseURL, regs),
	})

	// 4. steamcmd/docker-compose.yml — DNS 加速 docker compose 模板
	files = append(files, bundleFile{
		path:    "steamcmd/docker-compose.yml",
		content: generateSteamCMDCompose(baseURL),
	})

	// 5. resource-accelerators/playwright.env
	files = append(files, bundleFile{
		path:    "resource-accelerators/playwright.env",
		content: generatePlaywrightEnv(baseURL),
	})

	// 6. resource-accelerators/puppeteer.env
	files = append(files, bundleFile{
		path:    "resource-accelerators/puppeteer.env",
		content: generatePuppeteerEnv(baseURL),
	})

	// 7. resource-accelerators/terraformrc
	files = append(files, bundleFile{
		path:    "resource-accelerators/terraformrc",
		content: generateTerraformRC(baseURL),
	})

	// 8. resource-accelerators/helm-repos.sh
	files = append(files, bundleFile{
		path:    "resource-accelerators/helm-repos.sh",
		content: generateHelmReposSh(baseURL),
	})

	// 9. verify.sh — 一键验证脚本
	files = append(files, bundleFile{
		path:    "verify.sh",
		content: generateVerifySh(baseURL, regs, now),
	})

	// 10. README.md — 用户引导
	files = append(files, bundleFile{
		path:    "README.md",
		content: generateBundleReadme(baseURL, regs, now),
	})

	return files
}

// clientConfigContextFromURL 用已知 baseURL 构造 ctx（不需要 request）。
func clientConfigContextFromURL(baseURL string, reg storage.Registry, hostname string) clientConfigContext {
	mirrorPath := reg.MirrorPath
	if mirrorPath == "" {
		mirrorPath = "/v2"
	}
	return clientConfigContext{
		BaseURL:     baseURL,
		Registry:    reg,
		RegistryURL: baseURL + mirrorPath,
		Hostname:    hostname,
	}
}

// generateDockerDaemonJSON 生成包含所有 enabled upstreams 的 daemon.json。
func generateDockerDaemonJSON(baseURL string, regs []storage.Registry) []byte {
	mirrors := []string{}
	insecure := []string{}
	for _, reg := range regs {
		if !reg.Enabled {
			continue
		}
		mirrorPath := reg.MirrorPath
		if mirrorPath == "" {
			mirrorPath = "/v2"
		}
		mirrors = append(mirrors, baseURL+mirrorPath)
		// 反代是 http → 客户端要 insecure-registries 加这个 host
		host := stripScheme(baseURL)
		if host != "" {
			insecure = append(insecure, host)
		}
	}
	// 去重
	mirrors = dedupStrings(mirrors)
	insecure = dedupStrings(insecure)

	body := fmt.Sprintf(`{
  "_comment": "Docker daemon config — generated by CNCacheHub",
  "_generated_at": %d,
  "_verify_cmd": "docker pull alpine:latest && docker info | grep -A5 'Registry Mirrors'",
  "registry-mirrors": [%s
  ],
  "insecure-registries": [%s
  ]
}
`, nowUnix(), joinQuoted(mirrors, "  "), joinQuoted(insecure, "  "))
	return []byte(body)
}

// generateK3sRegistriesYAMLMulti 生成 k3s registries.yaml 含所有 enabled upstreams。
func generateK3sRegistriesYAMLMulti(baseURL string, regs []storage.Registry) []byte {
	var b bytes.Buffer
	b.WriteString("# k3s / rke2 registries.yaml — generated by CNCacheHub\n")
	b.WriteString("# 目标路径：/etc/rancher/k3s/registries.yaml\n")
	b.WriteString("# 适用：k3s / rke2 / K8s containerd runtime\n")
	b.WriteString("#\n")
	b.WriteString("# 安装步骤：\n")
	b.WriteString("#   1. 写入到 /etc/rancher/k3s/registries.yaml\n")
	b.WriteString("#   2. systemctl restart k3s\n")
	b.WriteString("#   3. 验证：crictl pull alpine:latest\n")
	b.WriteString("#\n")
	b.WriteString("mirrors:\n")
	hasAny := false
	for _, reg := range regs {
		if !reg.Enabled {
			continue
		}
		host := registryHostnameFromUpstream(reg.Name)
		fmt.Fprintf(&b, "  %q:\n", host)
		fmt.Fprintf(&b, "    endpoint:\n")
		fmt.Fprintf(&b, "      - %q\n", baseURL)
		hasAny = true
	}
	if !hasAny {
		b.WriteString("  # (no enabled upstreams — 在 Web UI 启用至少一个 registry)\n")
	}
	return b.Bytes()
}

// generateSteamCMDCompose 生成 SteamCMD docker-compose 模板。
//
// 用法：用户拷贝后 docker compose up -d steamcmd，然后在容器内跑 steamcmd。
// 通过 dns 字段指向 CNCacheHub 内置 DNS（5353）让 Steam 走 CNCH 加速。
func generateSteamCMDCompose(baseURL string) []byte {
	cnchIP := "host.docker.internal" // Docker Desktop 风格；Linux 下需要 extra_hosts
	return []byte(fmt.Sprintf(`# SteamCMD Docker Compose — generated by CNCacheHub
# 用法：
#   1. cd steamcmd/
#   2. docker compose up -d
#   3. docker compose exec steamcmd bash -c "steamcmd +login anonymous +force_install_dir /home/steam/csgo +app_update 740 validate +quit"
#
# 加速原理：让容器 DNS 走 CNCacheHub 内置的 mini DNS（UDP 5353），
# 把 *.steamcontent.com / *.steamstatic.com 等 Steam 域名劫持到 CNCH。
# 注意：CNCacheHub DNS server 监听 0.0.0.0:5353（非标准 53 端口，免 root）。

services:
  steamcmd:
    image: cm2network/steamcmd:root
    container_name: cnch-steamcmd
    restart: unless-stopped
    # 把 CNCH 监听地址告诉容器：Linux 上需在 host 上跑 CNCH 监听 5353
    extra_hosts:
      - "cncachehub:%s"
    # 让容器走 CNCH 的 DNS
    dns:
      - %s
    environment:
      # CNCH base URL（容器内可通过 extra_hosts 解析；可改成实际 IP）
      CNCH_BASE_URL: "%s"
    volumes:
      - ./data:/home/steam/data
    tty: true
    stdin_open: true
`, cnchIP, cnchIP, baseURL))
}

