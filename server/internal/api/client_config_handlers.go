// generateClientConfigBundleHandler POST /api/client-config/bundle
//
// 流式返回 .zip — 公开端点（跟 /api/client-config 一样）。
func generateClientConfigBundleHandler(opts Options) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		if opts.ListRegistries == nil {
			writeError(w, http.StatusServiceUnavailable, "client_config_unavailable", "registries not configured")
			return
		}
		regs, err := opts.ListRegistries(r.Context())
		if err != nil {
			writeInternalErr(w, r, "registries_query_failed", err)
			return
		}
		base := clientBaseURL(opts, r)
		files := buildClientConfigBundle(base, regs)

		// 写 zip header
		filename := fmt.Sprintf("cncachehub-client-config-%s.zip", time.Now().UTC().Format("20060102-150405"))
		w.Header().Set("Content-Type", "application/zip")
		w.Header().Set("Content-Disposition", `attachment; filename="`+filename+`"`)
		w.WriteHeader(http.StatusOK)

		// 构造 zip（写到内存 — bundle 10 个文件很小 < 10KB）
		var buf bytes.Buffer
		zw := zip.NewWriter(&buf)
		for _, f := range files {
			h := &zip.FileHeader{
				Name:     f.path,
				Modified: time.Unix(timeNowUnix(), 0),
				Method:   zip.Deflate,
			}
			fw, err := zw.CreateHeader(h)
			if err != nil {
				continue // best-effort
			}
			_, _ = fw.Write(f.content)
		}
		_ = zw.Close()

		// 流式写
		_, _ = w.Write(buf.Bytes())
	}
}

// === helpers ===

func dedupStrings(in []string) []string {
	seen := make(map[string]struct{}, len(in))
	out := make([]string, 0, len(in))
	for _, s := range in {
		if _, ok := seen[s]; ok {
			continue
		}
		seen[s] = struct{}{}
		out = append(out, s)
	}
	return out
}

func joinQuoted(items []string, indent string) string {
	if len(items) == 0 {
		return ""
	}
	var b strings.Builder
	for i, s := range items {
		if i > 0 {
			b.WriteString(",\n")
		}
		b.WriteString(indent)
		fmt.Fprintf(&b, "%q", s)
	}
	return b.String()
}

func stripScheme(url string) string {
	if i := strings.Index(url, "://"); i >= 0 {
		return url[i+3:]
	}
	return url
}
